"""Canonical hashing and request fingerprints shared by idempotency callers."""

import hashlib
import json

from django.core.files.uploadedfile import UploadedFile


def file_fingerprint(upload):
    """Hash a complete upload in bounded chunks without consuming its stream."""
    position = upload.tell()
    checksum = hashlib.sha256()
    try:
        upload.seek(0)
        while chunk := upload.read(64 * 1024):
            checksum.update(chunk)
    finally:
        upload.seek(position)
    return {
        "name": upload.name,
        "content_type": upload.content_type,
        "size": upload.size,
        "sha256": checksum.hexdigest(),
    }

def digest(value):
    """Hash a JSON-compatible value independently of dictionary key order."""
    encoded = json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=True)
    return hashlib.sha256(encoded.encode("utf-8")).hexdigest()


def fingerprint(request):
    """Fingerprint a DRF JSON or form request within its managed scope.

    Includes body and query parameters. Object and query
    key order are ignored; array and repeated query value order are preserved.
    User isolation is handled by the service; the decorator adds method and path
    to the final fingerprint to prevent cross-resource replay within an operation.
    """
    body = request.data
    if hasattr(body, "lists"):
        # Preserve repeated fields and files. Type tags distinguish text from files;
        # parsed content ignores the random boundary generated by multipart clients.
        body = {
            "form": [
                [name, [
                    {"file": file_fingerprint(value)} if isinstance(value, UploadedFile)
                    else {"text": value}
                    for value in values
                ]]
                for name, values in sorted(body.lists())
            ]
        }
        return digest({
            "format": "form",
            "body": body,
            "query": sorted(request.query_params.lists()),
        })
    return digest({
        "body": body,
        "query": sorted(request.query_params.lists()),
    })
